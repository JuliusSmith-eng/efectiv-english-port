// ===== Мова сайту: рушій перекладу (UA / EN) =====
(function () {
  let currentLang = "uk";

  function applyLanguage(lang) {
    if (!translations[lang]) lang = "uk";
    currentLang = lang;
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = translations[lang][key];
      if (val !== undefined) el.innerHTML = val;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const val = translations[lang][key];
      if (val !== undefined) el.setAttribute("placeholder", val);
    });

    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.lang === lang);
    });

    try {
      localStorage.setItem("site_lang", lang);
    } catch (e) {
      /* localStorage недоступний — ігноруємо */
    }

    // Повідомляємо інші скрипти (teacher.js, script.js) про зміну мови
    window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  function initLang() {
    let saved = null;
    try {
      saved = localStorage.getItem("site_lang");
    } catch (e) {
      /* ignore */
    }
    // Мова за замовчуванням — англійська. Якщо користувач вже обирав
    // мову раніше (є збережене значення), використовуємо його.
    const lang = saved || "en";
    applyLanguage(lang);
  }

  document.addEventListener("click", (e) => {
    const btn = e.target.closest(".lang-btn");
    if (!btn) return;
    applyLanguage(btn.dataset.lang);
  });

  // Публічний доступ для інших скриптів сайту
  window.siteI18n = {
    apply: applyLanguage,
    get lang() {
      return currentLang;
    },
    t: (key) =>
      (translations[currentLang] && translations[currentLang][key]) || key,
  };

  document.addEventListener("DOMContentLoaded", initLang);
})();
